#!/usr/bin/env node
/**
 * One-off generator for src/data/bodyPaths.ts.
 *
 *   node scripts/musclemap-paths.mjs <path to a MuscleMap checkout>
 *
 * Reads MuscleMap's male front/back path tables
 * (Sources/MuscleMap/Data/MaleFrontPaths.swift, MaleBackPaths.swift) and the
 * male view boxes (BodyPathData.swift), and writes the body outlines as plain
 * data: per view, one SVG path string per slug (common + left + right joined).
 *
 * MuscleMap is MIT licensed, Copyright (c) 2026 Melih Colpan
 * (https://github.com/melihcolpan/MuscleMap). See THIRD_PARTY_NOTICES.md.
 * Only the path strings and slug names are taken; no Swift code.
 *
 * Sub-slugs that merely re-cut a region already covered by its parent
 * (upper/lower chest, inner/outer quad, ...) are left out: they overlap the
 * parent and would only add weight.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SKIP = new Set([
  'upperChest', 'lowerChest', 'innerQuad', 'outerQuad', 'upperAbs', 'lowerAbs',
  'frontDeltoid', 'rearDeltoid', 'upperTrapezius', 'lowerTrapezius',
]);

/**
 * MuscleMap's own view boxes leave a wide margin (the arms and hands sit well
 * inside them). Tight bounds of the drawn paths plus up to 15 units of padding (top edge is MuscleMap's own),
 * measured with getBBox in a browser, so small renders spend their pixels on
 * the body. Keep in step with the paths if they are ever regenerated from a
 * different MuscleMap version: the MuscleMap box is still read and checked
 * to contain the crop.
 */
const CROP = { front: [38, 95, 652, 1260], back: [758, 95, 651, 1262] };

const root = process.argv[2];
if (!root) {
  console.error('usage: node scripts/musclemap-paths.mjs <MuscleMap checkout>');
  process.exit(1);
}
const data = join(root, 'Sources/MuscleMap/Data');

function parseViewBox(src, name) {
  const m = src.match(
    new RegExp(
      `static let ${name}\\s*=\\s*BodyViewBox\\(\\s*origin:\\s*CGPoint\\(x:\\s*([\\d.]+),\\s*y:\\s*([\\d.]+)\\),\\s*size:\\s*CGSize\\(width:\\s*([\\d.]+),\\s*height:\\s*([\\d.]+)\\)`,
    ),
  );
  if (!m) throw new Error(`view box ${name} not found`);
  return m.slice(1, 5).map(Number);
}

function parsePaths(src) {
  const out = {};
  for (const block of src.split('BodyPartPathData(').slice(1)) {
    const slug = block.match(/slug:\s*\.(\w+)/)?.[1];
    if (!slug || SKIP.has(slug)) continue;
    const strings = [...block.matchAll(/"([^"]+)"/g)].map((m) => m[1].trim());
    out[slug] = strings.join(' ');
  }
  return out;
}

const bodyData = readFileSync(join(data, 'BodyPathData.swift'), 'utf8');
const views = {
  front: {
    viewBox: parseViewBox(bodyData, 'maleFront'),
    paths: parsePaths(readFileSync(join(data, 'MaleFrontPaths.swift'), 'utf8')),
  },
  back: {
    viewBox: parseViewBox(bodyData, 'maleBack'),
    paths: parsePaths(readFileSync(join(data, 'MaleBackPaths.swift'), 'utf8')),
  },
};

for (const k of Object.keys(views)) {
  const [x, y, w, h] = views[k].viewBox;
  const [cx, cy, cw, ch] = CROP[k];
  if (cx < x || cy < y || cx + cw > x + w || cy + ch > y + h) {
    throw new Error(`${k} crop falls outside MuscleMap's view box`);
  }
  views[k].viewBox = CROP[k];
}

const header = `/**
 * Body outlines, generated by scripts/musclemap-paths.mjs. Do not edit by hand.
 *
 * Source: MuscleMap (male front/back path data and view boxes),
 * https://github.com/melihcolpan/MuscleMap
 * MIT License, Copyright (c) 2026 Melih Colpan. Full licence text in
 * THIRD_PARTY_NOTICES.md.
 */
`;
const body = `
export interface BodyView {
  /** x, y, width, height of the drawing's own coordinate space. */
  viewBox: [number, number, number, number];
  /** One SVG path (both sides of the body) per MuscleMap slug. */
  paths: Record<string, string>;
}

export const BODY_VIEWS: { front: BodyView; back: BodyView } = ${JSON.stringify(views)};
`;
const outFile = join(fileURLToPath(new URL('.', import.meta.url)), '../src/data/bodyPaths.ts');
writeFileSync(outFile, header + body);
console.log(`wrote ${outFile}`);
for (const [k, v] of Object.entries(views)) console.log(k, Object.keys(v.paths).join(' '));
